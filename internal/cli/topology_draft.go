const draftSpecHeader = `# nyx draft spec, generated by ` + "`nyx topology --draft-spec`" + `.
# PRIVATE: this file contains real addresses from your network. Keep it
# under the gitignored specs/ directory and never commit it.
# Review every TODO, rename the vlan<id> networks to their roles
# (docs/naming.md), then run ` + "`nyx audit --spec <file>`" + `.
version: 1
site: draft # TODO: name this site
`

// renderDraftSpec drafts an intent spec from a detail+matrix fingerprint:
// one network per segment with an observed subnet, probe candidates as
// commented suggestions, and a commented isolation suggestion per pair no
// rule names. vantageCIDRs are the networks this machine is attached to.
// Suggestions are written as "# " + the exact YAML line, so uncommenting a
// block yields valid YAML without duplicate keys.
func renderDraftSpec(fp *topology.Fingerprint, vantageCIDRs []string) []byte {
	var b bytes.Buffer
	b.WriteString(draftSpecHeader)
	vantage := vantageSet(vantageCIDRs)

	b.WriteString("networks:\n")
	var probes []string
	for _, s := range fp.Segments {
		if s.Detail == nil {
			fmt.Fprintf(&b, "  # VLAN %d: observed by %s, but no subnet was observed; add it by hand\n", s.VLAN, strings.Join(s.ObservedBy, " and "))
			continue
		}
		name := draftNetworkName(s.VLAN)
		attached := vantage[maskedPrefix(s.Detail.CIDR)]
		if attached {
			fmt.Fprintf(&b, "  # vantage: this machine is attached to %s\n", name)
		}
		fmt.Fprintf(&b, "  - name: %s\n    vlan: %d\n    cidr: %s\n    gateway: %s\n", name, s.VLAN, s.Detail.CIDR, s.Detail.GatewayAddress)
		fmt.Fprintf(&b, "    zone: %s # TODO: set the zone role (docs/naming.md)\n", name)
		if s.Gateway != "" {
			fmt.Fprintf(&b, "    # edge: %s # fingerprint: %s serves this VLAN's gateway\n", s.Gateway, s.Gateway)
		}
		if !attached && len(s.Detail.ProbeCandidates) > 0 {
			probes = append(probes, draftProbe(name, s.Detail.ProbeCandidates[0]))
		}
	}
	b.WriteString("policies: []\n")

	if len(probes) > 0 {
		b.WriteString("# Probe suggestions from inventory, one per segment this machine is not on.\n")
		b.WriteString("# To use one, uncomment the block and set user (and key) for the host.\n")
		b.WriteString("# probes:\n")
		for _, p := range probes {
			b.WriteString(p)
		}
	}
	if isolation := draftIsolation(fp); isolation != "" {
		b.WriteString("# Isolation suggestions for segment pairs no rule names. Confirm each\n")
		b.WriteString("# verdict before uncommenting: allow may be the intended answer.\n")
		b.WriteString("# assertions:\n")
		b.WriteString(isolation)
	}
	return b.Bytes()
}

func draftNetworkName(vlan int) string { return fmt.Sprintf("vlan%d", vlan) }

func draftProbe(network string, c topology.ProbeCandidate) string {
	origin := c.Source + " inventory"
	if c.Hostname != "" {
		origin += " (" + c.Hostname + ")"
	}
	return fmt.Sprintf("#   - name: %s-probe\n#     host: %s # candidate from %s; unverified\n#     user: <your-user>\n#     vlan: %s\n",
		network, c.Address, origin, network)
}

// draftIsolation suggests an isolation assertion for each uncovered pair
// whose segments both made it into the draft.
func draftIsolation(fp *topology.Fingerprint) string {
	if fp.Matrix == nil {
		return ""
	}
	drafted := map[int]bool{}
	for _, s := range fp.Segments {
		drafted[s.VLAN] = s.Detail != nil
	}
	var b strings.Builder
	for _, pair := range fp.Matrix.Uncovered() {
		if !drafted[pair[0]] || !drafted[pair[1]] {
			continue
		}
		from, to := draftNetworkName(pair[0]), draftNetworkName(pair[1])
		fmt.Fprintf(&b, "#   - type: isolation\n#     from: %s\n#     to: %s\n#     expect: deny # TODO: no rule names %s -> %s; confirm the intended verdict\n",
			from, to, from, to)
	}
	return b.String()
}

func vantageSet(cidrs []string) map[netip.Prefix]bool {
	set := make(map[netip.Prefix]bool, len(cidrs))
	for _, c := range cidrs {
		if p := maskedPrefix(c); p.IsValid() {
			set[p] = true
		}
	}
	return set
}

func maskedPrefix(cidr string) netip.Prefix {
	p, err := netip.ParsePrefix(strings.TrimSpace(cidr))
	if err != nil {
		return netip.Prefix{}
	}
	return p.Masked()
}

// writeDraftSpec writes the draft owner-only. It refuses to replace an
// existing file unless force is set.
func writeDraftSpec(path string, draft []byte, force bool) error {
	if force {
		return filewrite.Write(path, bytes.NewReader(draft))
	}
	err := filewrite.Create(path, bytes.NewReader(draft))
	if errors.Is(err, fs.ErrExist) {
		return fmt.Errorf("draft spec %s already exists: choose another path, or pass --force to replace it", path)
	}
	return err
}

// localVantageCIDRs lists the networks this machine is attached to, for the
// draft's vantage marker. A detection failure yields no CIDRs, which only
// drops the marker.
var localVantageCIDRs = func() []string {
	local, _ := detectLocalCIDRs("")
	out := make([]string, 0, len(local))
	for _, l := range local {
		out = append(out, l.cidr)
	}
	return out
}

// draftSpecNotice is printed after the draft is written.
func draftSpecNotice(path string) string {
	return fmt.Sprintf("Draft spec written to %s. It contains private addresses: keep it under the gitignored specs/ directory.", path)
}
