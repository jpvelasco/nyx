func TestBuildInitSpec_ScanModePolite(t *testing.T) {
	nets := []initNet{
		{cidr: "10.0.0.0/24", gateway: "10.0.0.1", localIP: "10.0.0.5", hosts: 3, ifaceName: "eth0"},
		{cidr: "10.0.10.0/24", gateway: "10.0.10.1", localIP: "10.0.10.5", hosts: 0, ifaceName: "eth1"},
	}
	spec := buildInitSpec(nets)
	if len(spec.Networks) != 2 {
		t.Fatalf("networks = %d, want 2", len(spec.Networks))
	}
	found := false
	for _, a := range spec.Assertions {
		if a.Type != "subnet_discovery" {
			continue
		}
		found = true
		// Generated specs must default to polite scans: normal/aggressive
		// modes trigger SYN-flood alarms on SDN controllers.
		if a.ScanMode != "polite" {
			t.Errorf("subnet_discovery %q scan_mode = %q, want %q", a.Network, a.ScanMode, "polite")
		}
	}
	if !found {
		t.Errorf("no subnet_discovery assertions in generated spec")
	}
}

func TestHostCountFrom(t *testing.T) {
	tests := []struct {
		name   string
		result *models.CheckResult
		want   int
	}{
		{"nil result", nil, 0},
		{"no observed key", &models.CheckResult{Observed: map[string]interface{}{}}, 0},
		{"int total", &models.CheckResult{Observed: map[string]interface{}{"total": 7}}, 7},
		{"float64 total", &models.CheckResult{Observed: map[string]interface{}{"total": float64(12)}}, 12},
		{"wrong type", &models.CheckResult{Observed: map[string]interface{}{"total": "seven"}}, 0},
		{"hosts_up ignored", &models.CheckResult{Observed: map[string]interface{}{"hosts_up": 5, "total": 3}}, 3},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := hostCountFrom(tc.result); got != tc.want {
				t.Errorf("hostCountFrom() = %d, want %d", got, tc.want)
			}
		})
	}
}

// fakeNmapOnPATH installs an inert executable named nmap on the test PATH.
// It exits 0 with empty output: the scanner's discovery reports no hosts
// (init tolerates that) without any real network activity.
func fakeNmapOnPATH(t *testing.T) {
	t.Helper()
	dir := t.TempDir()
	name := "nmap"
	script := "#!/bin/sh\nexit 0\n"
	if runtime.GOOS == "windows" {
		name = "nmap.bat"
		script = "@echo off\r\nexit /b 0\r\n"
	}
	path := filepath.Join(dir, name)
	if err := os.WriteFile(path, []byte(script), 0o700); err != nil {
		t.Fatalf("writing fake nmap: %v", err)
	}
	t.Setenv("PATH", dir+string(os.PathListSeparator)+os.Getenv("PATH"))
}

// TestInitCmd_FailedInitPreservesExistingSpec reproduces #188: a failed
// init (invalid --interface) must not truncate an existing output spec.
// The file is only replaced atomically after a successful generation.
func TestInitCmd_FailedInitPreservesExistingSpec(t *testing.T) {
	saveRestoreGlobals(t)
	fakeNmapOnPATH(t)

	existing := filepath.Join(t.TempDir(), "nyx.yaml")
	const original = "# my existing spec — must survive a failed init\n"
	if err := os.WriteFile(existing, []byte(original), 0600); err != nil {
		t.Fatalf("seeding existing spec: %v", err)
	}

	initOutput = existing
	defer func() { initOutput = "" }()
	interfaceOpt = "__bogus_iface__"
	defer func() { interfaceOpt = "" }()

	if err := initCmd.RunE(initCmd, nil); err == nil {
		t.Fatal("expected error for unknown interface")
	}
	got, err := os.ReadFile(existing) // nosemgrep: go_filesystem_rule-fileread — fixed test fixture path
	if err != nil {
		t.Fatalf("reading existing spec: %v", err)
	}
	if string(got) != original {
		t.Errorf("existing spec was modified by a failed init: %q", got)
	}

	// No temporary siblings may be left behind either.
	entries, err := os.ReadDir(filepath.Dir(existing))
	if err != nil {
		t.Fatalf("ReadDir: %v", err)
	}
	if len(entries) != 1 {
		names := []string{}
		for _, e := range entries {
			names = append(names, e.Name())
		}
		t.Errorf("failed init left files behind: %v", names)
	}
}

// TestInitCmd_SuccessWritesOutputAtomically pins the success path: the
// generated spec replaces the target only after a complete write, and no
// temporary sibling remains.
func TestInitCmd_SuccessWritesOutputAtomically(t *testing.T) {
	saveRestoreGlobals(t)
	fakeNmapOnPATH(t)

	outPath := filepath.Join(t.TempDir(), "nyx.yaml")
	initOutput = outPath
	defer func() { initOutput = "" }()
	interfaceOpt = ""
	defer func() { interfaceOpt = "" }()

	if err := initCmd.RunE(initCmd, nil); err != nil {
		t.Fatalf("init failed: %v", err)
	}
	got, err := os.ReadFile(outPath) // nosemgrep: go_filesystem_rule-fileread — fixed test fixture path
	if err != nil {
		t.Fatalf("reading generated spec: %v", err)
	}
	if !strings.Contains(string(got), "Generated by nyx init") {
		t.Errorf("output file does not contain a generated spec: %q", got)
	}
	entries, err := os.ReadDir(filepath.Dir(outPath))
	if err != nil {
		t.Fatalf("ReadDir: %v", err)
	}
	if len(entries) != 1 {
		t.Errorf("init left temporary files behind: %d entries", len(entries))
	}
}
